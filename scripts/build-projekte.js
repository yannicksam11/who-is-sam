const fs = require('fs');
const path = require('path');
const matter = require('gray-matter');

const PROJEKTE_DIR = path.join(__dirname, '..', '_projekte');
const OUTPUT_FILE = path.join(__dirname, '..', 'js', 'projekte-daten.js');

function slugFromFilename(filename) {
  return filename.replace(/\.md$/, '');
}

function readProjekte() {
  if (!fs.existsSync(PROJEKTE_DIR)) return [];

  return fs.readdirSync(PROJEKTE_DIR)
    .filter((filename) => filename.endsWith('.md'))
    .sort()
    .map((filename) => {
      const raw = fs.readFileSync(path.join(PROJEKTE_DIR, filename), 'utf8');
      const { data } = matter(raw);

      return {
        id: slugFromFilename(filename),
        projekt: data.projekt || '',
        massstab: data.massstab || '',
        kunde: data.kunde || '',
        format: data.format || 'quer',
        titelbild: data.titelbild || '',
        weitereBilder: (data.weitereBilder || [])
          .map((item) => (typeof item === 'string' ? item : item.bild))
          .filter(Boolean)
      };
    });
}

function serialize(projekte) {
  const header = '// Auto-generated by scripts/build-projekte.js — do not edit by hand.\n' +
    '// Source: markdown files in _projekte/, managed via /admin (Decap CMS).\n\n';
  const body = `const PROJEKTE = ${JSON.stringify(projekte, null, 2)};\n\nwindow.PROJEKTE = PROJEKTE;\n`;
  return header + body;
}

const projekte = readProjekte();
fs.writeFileSync(OUTPUT_FILE, serialize(projekte));
console.log(`Generated ${OUTPUT_FILE} with ${projekte.length} project(s).`);
